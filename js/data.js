  App.LV_TEXT = { ok: 'ปกติ', mid: 'เฝ้าระวัง', risk: 'เสี่ยง', wait: '' };

  App.evaluate = function (v) {
    var vt = v.vitals || {};
    var wt = parseFloat(vt.wt), htcm = parseFloat(vt.ht), age = parseInt(v.age, 10) || 0;
    var bmi = (wt > 0 && htcm > 0) ? wt / Math.pow(htcm / 100, 2) : NaN;
    var osta = wt > 0 && age ? 0.2 * (wt - age) : NaN;
    var ostaLv = isNaN(osta) ? '' : osta > -1 ? 'ต่ำ' : osta >= -4 ? 'ปานกลาง' : 'สูง';
    var sys = parseInt(vt.sys, 10), dia = parseInt(vt.dia, 10);
    var meds = parseInt(v.meds, 10);
    var c = { age: age, sex: v.sex, wt: wt, htcm: htcm, bmi: bmi, osta: osta, ostaLv: ostaLv, sys: sys, dia: dia,
      meds: isNaN(meds) ? 0 : meds, kneePain: (v.screen || {})['knee-0'] === true, mnasf: null,
      bpHigh: sys >= 140 || dia >= 90,
      bmiTxt: isNaN(bmi) ? '' : bmi.toFixed(1) };

    // 13 ข้อ: ข้อที่ระบบตอบให้
    var a = Object.assign({}, v.screen || {});
    a['nutr-0'] = isNaN(bmi) ? null : bmi < 18.5;
    a['nutr-1'] = isNaN(bmi) ? null : bmi >= 23;
    a['poly-0'] = isNaN(meds) ? null : meds > 4;

    var answered = 0, total = 0, risky = [];
    var domains = App.DOMAINS.map(function (d) {
      var anyYes = false, complete = true;
      d.items.forEach(function (t, i) {
        var val = a[d.id + '-' + i]; total++;
        if (val === true || val === false) answered++; else complete = false;
        if (val === true) anyYes = true;
      });
      var risk = d.invert ? a[d.id + '-0'] === false : anyYes;
      var lv = risk ? 'risk' : complete ? 'ok' : 'wait';
      if (risk) risky.push(d);
      return { d: d, lv: lv, result: risk ? d.pos : complete ? d.neg : 'ยังไม่ครบ' };
    });
    var ostaRisk = ostaLv === 'ปานกลาง' || ostaLv === 'สูง';

    // แบบละเอียด (MNA-SF ส่งคะแนนให้ Full form)
    var T = App.tools(c), byId = {};
    T.forEach(function (t) { byId[t.id] = t; });
    var det = v.detail || {};
    var sf = evalTool(byId.mnasf, det.mnasf, c);
    if (sf.done) { c.mnasf = sf.sum; T = App.tools(c); byId = {}; T.forEach(function (t) { byId[t.id] = t; }); }
    var results = {};
    T.forEach(function (t) { results[t.id] = evalTool(t, det[t.id], c); });

    var rec = {};
    risky.forEach(function (d) { if (d.tool) rec[d.tool] = true; });
    if (ostaRisk) rec.frax = true;
    Object.keys(results).forEach(function (k) { results[k].j.next.forEach(function (n) { rec[n] = true; }); });

    var detailText = [];
    T.forEach(function (t) { var r = results[t.id]; if (r.j.lv !== 'wait') detailText.push(t.name + ': ' + (t.noSum ? '' : r.sum + ' คะแนน · ') + r.j.res); });

    return {
      c: c, screen: a, domains: domains, answered: answered, total: total,
      riskCount: risky.length + (ostaRisk ? 1 : 0),
      riskNames: risky.map(function (d) { return d.title; }).concat(ostaRisk ? ['OSTA ' + ostaLv] : []),
      risky: risky, ostaRisk: ostaRisk, tools: T, byId: byId, results: results, rec: rec, detailText: detailText
    };
  };

